  for select to authenticated
  using (id = (select auth.uid()) or public.shares_household(id));

create policy "Update own profile" on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "Read own devices" on public.devices
  for select to authenticated
  using (user_id = (select auth.uid()));

create policy "Read own entitlement" on public.entitlements
  for select to authenticated
  using (user_id = (select auth.uid()));

create policy "Read accessible pets" on public.pets
  for select to authenticated
  using (public.can_access_pet(id));

create policy "Owner creates pet" on public.pets
  for insert to authenticated
  with check (owner_id = (select auth.uid()));

create policy "Owner updates pet" on public.pets
  for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "Owner deletes pet" on public.pets
  for delete to authenticated
  using (owner_id = (select auth.uid()));

create policy "Read tasks of accessible pets" on public.tasks
  for select to authenticated
  using (public.can_access_pet(pet_id));

create policy "Owner creates tasks" on public.tasks
  for insert to authenticated
  with check (public.is_pet_owner(pet_id));

-- No delete policy: tasks are archived by setting archived_at.
create policy "Owner updates tasks" on public.tasks
  for update to authenticated
  using (public.is_pet_owner(pet_id))
  with check (public.is_pet_owner(pet_id));

-- Read only for clients. Changes go through complete_occurrence() and undo_occurrence().
create policy "Read occurrences of accessible pets" on public.task_occurrences
  for select to authenticated
  using (public.can_access_pet(pet_id));

create policy "Read own household" on public.household_members
  for select to authenticated
  using (owner_id = (select auth.uid()) or public.is_member_of(owner_id));

-- The owner removes a member, or a member leaves.
create policy "Owner removes or member leaves" on public.household_members
  for delete to authenticated
  using (owner_id = (select auth.uid()) or member_id = (select auth.uid()));

create policy "Owner reads invites" on public.invites
  for select to authenticated
  using (owner_id = (select auth.uid()));

create policy "Owner cancels invites" on public.invites
  for delete to authenticated
  using (owner_id = (select auth.uid()));

create policy "Manage own notification prefs" on public.notification_prefs
  for all to authenticated
  using (user_id = (select auth.uid()) and public.can_access_pet(pet_id))
  with check (user_id = (select auth.uid()) and public.can_access_pet(pet_id));

-- ─── Triggers ───────────────────────────────────────────────────────────────

-- Create a profile for every new account.
create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', ''), 60)
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Reject unknown timezones, which would otherwise break the scheduled jobs for everyone.
create function public.validate_pet_timezone()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if not exists (select 1 from pg_catalog.pg_timezone_names where name = new.timezone) then
    raise exception 'Unknown timezone: %', new.timezone using errcode = '22023';
  end if;
  return new;
end;
$$;

create trigger validate_pet_timezone
  before insert or update of timezone on public.pets
  for each row execute function public.validate_pet_timezone();

-- starts_at is managed by the server: set on create, reset when the schedule changes.
create function public.set_task_starts_at()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.starts_at := now();
  elsif new.time_of_day is distinct from old.time_of_day
     or new.weekdays is distinct from old.weekdays then
    new.starts_at := now();
  else
    new.starts_at := old.starts_at;
  end if;
  return new;
end;
$$;

create trigger set_task_starts_at
  before insert or update on public.tasks
  for each row execute function public.set_task_starts_at();

-- Keep occurrences in step with the task: rebuild pending ones from today onward.
-- Done and missed occurrences are never touched.
create function public.sync_task_occurrences()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' then
    if new.title is not distinct from old.title
       and new.category is not distinct from old.category
       and new.time_of_day is not distinct from old.time_of_day
       and new.weekdays is not distinct from old.weekdays
       and new.archived_at is not distinct from old.archived_at then
      return null;
    end if;

    delete from public.task_occurrences o
    using public.pets p
    where o.task_id = new.id
      and p.id = o.pet_id
      and o.status = 'pending'
      and o.date >= (now() at time zone p.timezone)::date;
  end if;

  if new.archived_at is null then
    perform public.generate_occurrences(new.id);
  end if;
  return null;
end;
$$;

-- ─── Scheduling functions (called by triggers and pg_cron, not by the app) ──

-- Create occurrences from today (in each pet's timezone) up to p_days_ahead days out.
create function public.generate_occurrences(p_task_id uuid default null, p_days_ahead integer default 2)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_count integer;
begin
  insert into public.task_occurrences (task_id, pet_id, date, scheduled_at, title, category)
  select t.id, t.pet_id, d.day::date, (d.day::date + t.time_of_day) at time zone p.timezone, t.title, t.category
  from public.tasks t
  join public.pets p on p.id = t.pet_id
  cross join lateral generate_series(
    ((now() at time zone p.timezone)::date)::timestamp,
    ((now() at time zone p.timezone)::date + p_days_ahead)::timestamp,
    interval '1 day'
  ) as d (day)
  where t.archived_at is null
    and (p_task_id is null or t.id = p_task_id)
    and (t.weekdays & (1 << (extract(isodow from d.day)::integer - 1))) <> 0
    and ((d.day::date + t.time_of_day) at time zone p.timezone) >= t.starts_at
  on conflict (task_id, date) do nothing;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

create trigger sync_task_occurrences
  after insert or update on public.tasks
  for each row execute function public.sync_task_occurrences();

-- After midnight in the pet's timezone, anything still pending becomes missed.
create function public.mark_missed_occurrences()
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_count integer;
begin
  update public.task_occurrences o
  set status = 'missed'
  from public.pets p
  where p.id = o.pet_id
    and o.status = 'pending'
    and o.date < (now() at time zone p.timezone)::date;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- ─── App functions (called by the app through RPC) ──────────────────────────

-- Activate this install for the signed-in user.
-- Free accounts can be signed in on one phone at a time: if another phone is active,
-- this returns 'conflict' unless p_force is true, in which case the other phone is
-- deactivated and its sessions are revoked. Premium accounts have no device limit.
-- Returns 'ok' or 'conflict'.
create function public.register_device(p_device_id text, p_force boolean default false)
returns text
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id    uuid := auth.uid();
  v_session_id uuid := nullif(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'session_id', '')::uuid;
  v_premium    boolean;
begin
  if v_user_id is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;
  if p_device_id is null or char_length(p_device_id) not between 8 and 64 then
    raise exception 'Invalid device id' using errcode = '22023';
  end if;

  -- Serialize registrations for this user so two phones can't both win.
  perform pg_advisory_xact_lock(hashtextextended('register_device:' || v_user_id::text, 0));

  v_premium := public.is_premium(v_user_id);

  if not v_premium and not p_force and exists (
    select 1 from public.devices
    where user_id = v_user_id and device_id <> p_device_id and is_active
  ) then
    return 'conflict';
  end if;

  insert into public.devices (user_id, device_id, is_active, last_seen_at)
  values (v_user_id, p_device_id, true, now())
  on conflict (user_id, device_id) do update
    set is_active = true, last_seen_at = now();

  if not v_premium then
    update public.devices
    set is_active = false, apns_token = null
    where user_id = v_user_id and device_id <> p_device_id and is_active;

    -- Revoke every other session (their refresh tokens go with them), so the old
    -- phone is signed out the next time its access token expires or it checks in.
    if v_session_id is not null then
      delete from auth.sessions where user_id = v_user_id and id <> v_session_id;
    end if;
  end if;

  return 'ok';
end;
$$;

-- Check this install's status. Returns 'active', 'inactive' (signed in on another
-- phone) or 'unknown' (not registered yet).
create function public.device_status(p_device_id text)
returns text
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_active  boolean;
begin
  if v_user_id is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;

  update public.devices
  set last_seen_at = now()
  where user_id = v_user_id and device_id = p_device_id
  returning is_active into v_active;

  if v_active is null then
    return 'unknown';
  end if;
  return case when v_active then 'active' else 'inactive' end;
end;
$$;

-- Mark today's task as done, with an optional note and photo.
create function public.complete_occurrence(p_occurrence_id uuid, p_note text default null, p_photo_path text default null)
returns public.task_occurrences
language plpgsql security definer set search_path = ''
as $$
declare
  v_occurrence public.task_occurrences;
  v_timezone   text;
begin
  select * into v_occurrence from public.task_occurrences where id = p_occurrence_id for update;
  if not found or not public.can_access_pet(v_occurrence.pet_id) then
    raise exception 'Task not found' using errcode = 'P0002';
  end if;

  select timezone into v_timezone from public.pets where id = v_occurrence.pet_id;
  if v_occurrence.date <> (now() at time zone v_timezone)::date then
    raise exception 'Tasks can only be marked on their own day' using errcode = 'P0001';
  end if;
  if v_occurrence.status <> 'pending' then
    raise exception 'This task is already marked' using errcode = 'P0001';
  end if;

  update public.task_occurrences
  set status = 'done', completed_by = auth.uid(), completed_at = now(),
      note = nullif(btrim(p_note), ''), photo_path = p_photo_path
  where id = p_occurrence_id
  returning * into v_occurrence;

  return v_occurrence;
end;
$$;

-- Undo your own check-off, on the same day only.
create function public.undo_occurrence(p_occurrence_id uuid)
returns public.task_occurrences
language plpgsql security definer set search_path = ''
as $$
declare
  v_occurrence public.task_occurrences;
  v_timezone   text;
begin
  select * into v_occurrence from public.task_occurrences where id = p_occurrence_id for update;
  if not found or not public.can_access_pet(v_occurrence.pet_id) then
    raise exception 'Task not found' using errcode = 'P0002';
  end if;
  if v_occurrence.status <> 'done' or v_occurrence.completed_by is distinct from auth.uid() then
    raise exception 'Only the person who marked this task can undo it' using errcode = 'P0001';
  end if;

  select timezone into v_timezone from public.pets where id = v_occurrence.pet_id;
  if v_occurrence.date <> (now() at time zone v_timezone)::date then
    raise exception 'Tasks can only be changed on their own day' using errcode = 'P0001';
  end if;

  update public.task_occurrences
  set status = 'pending', completed_by = null, completed_at = null, note = null, photo_path = null
  where id = p_occurrence_id
  returning * into v_occurrence;

  return v_occurrence;
end;
$$;

-- Create an invite link token. Premium only; members plus open invites can't exceed 2.
create function public.create_invite()
returns public.invites
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_invite  public.invites;
begin
  if v_user_id is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;
  if not public.is_premium(v_user_id) then
    raise exception 'Inviting people needs Premium' using errcode = 'P0001';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('household:' || v_user_id::text, 0));

  if (select count(*) from public.household_members where owner_id = v_user_id)
     + (select count(*) from public.invites
        where owner_id = v_user_id and accepted_at is null and expires_at > now()) >= 2 then
    raise exception 'You can invite up to 2 people' using errcode = 'P0001';
  end if;

  insert into public.invites (owner_id) values (v_user_id) returning * into v_invite;
  return v_invite;
end;
$$;

-- Join a household from an invite link. Returns the owner's user id.
create function public.accept_invite(p_token text)
returns uuid
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_invite  public.invites;
begin
  if v_user_id is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;

  select * into v_invite from public.invites where token = p_token for update;
  if not found or v_invite.accepted_at is not null or v_invite.expires_at <= now() then
    raise exception 'This invite link is invalid or has expired' using errcode = 'P0001';
  end if;
  if v_invite.owner_id = v_user_id then
    raise exception 'You can''t join your own household' using errcode = 'P0001';
  end if;
  if not public.is_premium(v_invite.owner_id) then
    raise exception 'This invite is no longer active' using errcode = 'P0001';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('household:' || v_invite.owner_id::text, 0));

  if (select count(*) from public.household_members where owner_id = v_invite.owner_id) >= 2 then
    raise exception 'This household is full' using errcode = 'P0001';
  end if;

  insert into public.household_members (owner_id, member_id)
  values (v_invite.owner_id, v_user_id)
  on conflict do nothing;

  update public.invites set accepted_by = v_user_id, accepted_at = now() where id = v_invite.id;
  return v_invite.owner_id;
end;
$$;

