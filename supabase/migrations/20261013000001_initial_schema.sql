-- PawDone v1 schema: tables, row level security and server-side functions.
-- See docs/PRODUCT_SPEC.md, section 5.

-- ─── Types ──────────────────────────────────────────────────────────────────

create type public.pet_species as enum ('dog', 'cat', 'bird', 'rabbit', 'fish', 'other');
create type public.pet_gender as enum ('male', 'female', 'unknown');
create type public.task_category as enum ('food', 'water', 'walk', 'medicine', 'grooming', 'play', 'cleanup', 'other');
create type public.occurrence_status as enum ('pending', 'done', 'missed');

-- ─── Tables ─────────────────────────────────────────────────────────────────

create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null default '' check (char_length(name) <= 60),
  avatar_path text,
  created_at  timestamptz not null default now()
);

-- One row per app install. device_id is generated by the app and kept in the Keychain.
-- Written only through register_device().
create table public.devices (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references auth.users (id) on delete cascade,
  device_id    text not null check (char_length(device_id) between 8 and 64),
  apns_token   text,
  is_active    boolean not null default true,
  last_seen_at timestamptz not null default now(),
  created_at   timestamptz not null default now(),
  unique (user_id, device_id)
);

-- Written only by the RevenueCat webhook, using the service role.
create table public.entitlements (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  is_premium boolean not null default false,
  product_id text,
  expires_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.pets (
  id         uuid primary key default gen_random_uuid(),
  owner_id   uuid not null references auth.users (id) on delete cascade,
  name       text not null check (char_length(name) between 1 and 40),
  species    public.pet_species not null,
  breed      text check (char_length(breed) <= 60),
  birth_date date,
  gender     public.pet_gender,
  photo_path text,
  notes      text check (char_length(notes) <= 1000),
  -- IANA timezone name, e.g. 'Asia/Kolkata'. All task times are in this timezone.
  timezone   text not null default 'UTC',
  created_at timestamptz not null default now()
);

-- v1: one pet per owner on both plans.
create unique index pets_one_per_owner on public.pets (owner_id);

create table public.tasks (
  id               uuid primary key default gen_random_uuid(),
  pet_id           uuid not null references public.pets (id) on delete cascade,
  title            text not null check (char_length(title) between 1 and 60),
  category         public.task_category not null,
  time_of_day      time not null,
  -- Repeat days as a bitmask: Mon = 1, Tue = 2, Wed = 4, … Sun = 64. 127 = every day.
  weekdays         smallint not null default 127 check (weekdays between 1 and 127),
  reminder_enabled boolean not null default true,
  instructions     text check (char_length(instructions) <= 500),
  -- No occurrence is created for a time before this. Reset when the schedule changes,
  -- so a task added at 3 PM for 8 AM starts tomorrow instead of showing as missed today.
  starts_at        timestamptz not null default now(),
  created_at       timestamptz not null default now(),
  -- Tasks are archived, never deleted, so past reports keep their history.
  archived_at      timestamptz
);

create index tasks_pet_id on public.tasks (pet_id) where archived_at is null;

-- One row per task per day. Title and category are copied in, so editing a task
-- never changes past reports.
create table public.task_occurrences (
  id               uuid primary key default gen_random_uuid(),
  task_id          uuid not null references public.tasks (id) on delete cascade,
  pet_id           uuid not null references public.pets (id) on delete cascade,
  date             date not null,
  scheduled_at     timestamptz not null,
  title            text not null,
  category         public.task_category not null,
  status           public.occurrence_status not null default 'pending',
  completed_by     uuid references auth.users (id) on delete set null,
  completed_at     timestamptz,
  note             text check (char_length(note) <= 500),
  photo_path       text,
  reminder_sent_at timestamptz,
  unique (task_id, date)
);

create index task_occurrences_pet_date on public.task_occurrences (pet_id, date);
create index task_occurrences_pending_due on public.task_occurrences (scheduled_at) where status = 'pending';

create table public.household_members (
  owner_id  uuid not null references auth.users (id) on delete cascade,
  member_id uuid not null references auth.users (id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (owner_id, member_id),
  check (owner_id <> member_id)
);

create index household_members_member on public.household_members (member_id);

create table public.invites (
  id          uuid primary key default gen_random_uuid(),
  owner_id    uuid not null references auth.users (id) on delete cascade,
  token       text not null unique default replace(gen_random_uuid()::text, '-', ''),
  expires_at  timestamptz not null default now() + interval '7 days',
  accepted_by uuid references auth.users (id) on delete set null,
  accepted_at timestamptz,
  created_at  timestamptz not null default now()
);

create index invites_owner on public.invites (owner_id);

create table public.notification_prefs (
  user_id           uuid not null references auth.users (id) on delete cascade,
  pet_id            uuid not null references public.pets (id) on delete cascade,
  reminders_enabled boolean not null default true,
  primary key (user_id, pet_id)
);

-- ─── Access helpers ─────────────────────────────────────────────────────────
-- security definer so they can be used inside policies without recursing into RLS.

create function public.is_premium(p_user_id uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.entitlements e
    where e.user_id = p_user_id
      and e.is_premium
      and (e.expires_at is null or e.expires_at > now())
  );
$$;

-- The pet's owner, or a member of the owner's household while the owner has Premium.
create function public.can_access_pet(p_pet_id uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.pets p
    where p.id = p_pet_id
      and (
        p.owner_id = auth.uid()
        or (
          exists (
            select 1 from public.household_members hm
            where hm.owner_id = p.owner_id and hm.member_id = auth.uid()
          )
          and public.is_premium(p.owner_id)
        )
      )
  );
$$;

create function public.is_pet_owner(p_pet_id uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.pets where id = p_pet_id and owner_id = auth.uid());
$$;

-- True when the current user is a member of p_owner_id's household.
create function public.is_member_of(p_owner_id uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.household_members
    where owner_id = p_owner_id and member_id = auth.uid()
  );
$$;

-- True when the current user and p_user_id belong to the same household.
create function public.shares_household(p_user_id uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.household_members hm
    where (hm.owner_id = auth.uid() and hm.member_id = p_user_id)
       or (hm.member_id = auth.uid() and hm.owner_id = p_user_id)
       or (
         hm.member_id = auth.uid()
         and exists (
           select 1 from public.household_members other
           where other.owner_id = hm.owner_id and other.member_id = p_user_id
         )
       )
  );
$$;

